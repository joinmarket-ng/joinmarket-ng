_PODLE_NONCE_DOMAIN = b"JoinMarket/PoDLE/nonce/v1"


def _rfc6979_nonce_candidates(private_key_bytes: bytes, message_hash: bytes) -> Iterator[int]:
    """Yield secp256k1 nonce candidates using RFC 6979 with HMAC-SHA256."""
    if len(private_key_bytes) != 32 or len(message_hash) != 32:
        raise PoDLEError("RFC 6979 inputs must be 32 bytes")

    # secp256k1 has qlen=256, so bits2octets is a 32-byte conditional reduction.
    reduced_hash = (int.from_bytes(message_hash, "big") % SECP256K1_N).to_bytes(32, "big")
    seed_material = private_key_bytes + reduced_hash
    value = b"\x01" * 32
    key = b"\x00" * 32

    key = hmac.new(key, value + b"\x00" + seed_material, hashlib.sha256).digest()
    value = hmac.new(key, value, hashlib.sha256).digest()
    key = hmac.new(key, value + b"\x01" + seed_material, hashlib.sha256).digest()
    value = hmac.new(key, value, hashlib.sha256).digest()

    while True:
        value = hmac.new(key, value, hashlib.sha256).digest()
        candidate = int.from_bytes(value, "big")
        if 1 <= candidate < SECP256K1_N:
            yield candidate
        key = hmac.new(key, value + b"\x00", hashlib.sha256).digest()
        value = hmac.new(key, value, hashlib.sha256).digest()


def _podle_nonce_candidates(
    private_key_bytes: bytes,
    utxo_str: str,
    index: int,
    p_bytes: bytes,
    p2_bytes: bytes,
) -> Iterator[int]:
    """Yield deterministic nonces bound to a versioned PoDLE transcript."""
    utxo_bytes = utxo_str.encode("utf-8")
    transcript = (
        _PODLE_NONCE_DOMAIN
        + len(utxo_bytes).to_bytes(4, "big")
        + utxo_bytes
        + index.to_bytes(1, "big")
        + p_bytes
        + p2_bytes
    )
    return _rfc6979_nonce_candidates(private_key_bytes, hashlib.sha256(transcript).digest())


def _compute_podle_response(
    private_key: CKey,
    nonce: int,
    challenge: bytes,
) -> bytes | None:
    """Compute ``s = nonce + challenge * key`` with libsecp256k1 key tweaks.

    The challenge is public, so reducing it in Python does not expose secret
    material. The secret multiplication and response addition are delegated to
    libsecp256k1's secret-key tweak operations instead of Python bigint
    arithmetic. ``None`` means the challenge or resulting response is zero and
    the caller must retry.
    """
    challenge_scalar = int.from_bytes(challenge, "big") % SECP256K1_N
    if challenge_scalar == 0:
        return None
    try:
        multiplied_key = private_key.multiply(challenge_scalar.to_bytes(32, "big"))
        nonce_key = CKey(nonce.to_bytes(32, "big"))
        return CKey.add(multiplied_key, nonce_key).secret_bytes
    except ValueError:
        # secp256k1 rejects the zero response, matching the protocol retry rule.
        return None


def generate_podle(
    private_key_bytes: bytes,
    utxo_str: str,
    index: int = 0,
    *,
    p2tr: bool = False,
) -> PoDLECommitment:
    """
    Generate a PoDLE commitment for a UTXO.

    The PoDLE proves that the taker owns the UTXO without revealing
    the private key. It creates a zero-knowledge proof that:
    P = k*G and P2 = k*J have the same discrete log k.

    Args:
        private_key_bytes: 32-byte private key
        utxo_str: UTXO reference as "txid:vout"
        index: NUMS point index (0-255)
        p2tr: Derive the parity-normalized BIP86 output key before proving ownership

    Returns:
        PoDLECommitment with all proof data
    """
    if len(private_key_bytes) != 32:
        raise PoDLEError(f"Invalid private key length: {len(private_key_bytes)}")

    if not 0 <= index <= 255:
        raise PoDLEError(f"Invalid NUMS index: {index} (must be 0-255)")

    try:
        private_key = CKey(private_key_bytes)
    except ValueError as exc:
        raise PoDLEError("Invalid private key value") from exc

    if p2tr:
        try:
            tweaked_key = taproot_tweak_privkey(private_key_bytes)
            private_key = CKey(tweaked_key)
            if bytes(private_key.pub)[0] == 0x03:
                private_key = private_key.negated()
            private_key_bytes = private_key.secret_bytes
        except ValueError as exc:
            raise PoDLEError("Failed to derive BIP86 PoDLE key") from exc

    # Calculate P = k*G (standard public key)
    p_point = private_key.pub
    p_bytes = point_to_bytes(p_point)

    # Get NUMS point J
    j_point = get_nums_point(index)

    # Calculate P2 = k*J
    p2_point = j_point.multiply(private_key_bytes)
    p2_bytes = point_to_bytes(p2_point)

    # Generate commitment C = H(P2)
    commitment = hashlib.sha256(p2_bytes).digest()

    # Derive the nonce from the secret key and proof transcript. This removes
    # runtime RNG failures from a Schnorr-style operation where nonce reuse
    # across two proofs would reveal the UTXO private key.
    s_bytes: bytes | None = None
    for k_proof in _podle_nonce_candidates(
        private_key_bytes,
        utxo_str,
        index,
        p_bytes,
        p2_bytes,
    ):
        kg_bytes = point_to_bytes(scalar_mult_g(k_proof))
        kj_bytes = point_to_bytes(point_mult(k_proof, j_point))
        e_bytes = hashlib.sha256(kg_bytes + kj_bytes + p_bytes + p2_bytes).digest()
        s_bytes = _compute_podle_response(private_key, k_proof, e_bytes)
        if s_bytes is not None:
            break
    if s_bytes is None:
        raise PoDLEError("PoDLE nonce candidates exhausted")

    logger.bind(sensitive=True).debug(
        f"Generated PoDLE for {utxo_str} using NUMS index {index}, "
        f"commitment={commitment.hex()[:16]}..."
    )

    return PoDLECommitment(
        commitment=commitment,
        p=p_bytes,
        p2=p2_bytes,
        sig=s_bytes,
        e=e_bytes,
        utxo=utxo_str,
        index=index,
    )


