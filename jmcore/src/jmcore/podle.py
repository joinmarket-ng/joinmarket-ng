def parse_podle_revelation(revelation: dict[str, Any]) -> dict[str, Any] | None:
    """
    Parse and validate PoDLE revelation structure.

    Expected format from taker:
    {
        'P': <hex string>,
        'P2': <hex string>,
        'sig': <hex string>,
        'e': <hex string>,
        'utxo': <txid:vout or txid:vout:scriptpubkey:blockheight string>
    }

    Returns parsed structure with bytes, or None if invalid.
    Extended format includes scriptpubkey and blockheight for neutrino_compat feature.
    """
    try:
        required_fields = ["P", "P2", "sig", "e", "utxo"]
        for field in required_fields:
            if field not in revelation:
                logger.warning(f"Missing required field in PoDLE revelation: {field}")
                return None

        if not _has_valid_revelation_field_lengths(revelation):
            return None

        p_bytes = bytes.fromhex(revelation["P"])
        p2_bytes = bytes.fromhex(revelation["P2"])
        sig_bytes = bytes.fromhex(revelation["sig"])
        e_bytes = bytes.fromhex(revelation["e"])

        try:
            utxo = UTXOMetadata.from_str(revelation["utxo"])
            txid = utxo.txid
            vout = utxo.vout
            scriptpubkey = utxo.scriptpubkey
            blockheight = utxo.blockheight
            if scriptpubkey:
                logger.bind(sensitive=True).debug(
                    f"Parsed extended UTXO format: {txid}:{vout} with metadata"
                )
        except (ValueError, ValidationError):
            logger.warning("Invalid UTXO format in PoDLE revelation")
            logger.bind(sensitive=True).warning(
                f"Invalid UTXO format in PoDLE revelation: {revelation['utxo']}"
            )
            return None

        result: dict[str, Any] = {
            "P": p_bytes,
            "P2": p2_bytes,
            "sig": sig_bytes,
            "e": e_bytes,
            "txid": txid,
            "vout": vout,
        }

        # Add extended metadata if present
        if scriptpubkey is not None:
            result["scriptpubkey"] = scriptpubkey
        if blockheight is not None:
            result["blockheight"] = blockheight

        return result

    except Exception as e:
        logger.error("Failed to parse PoDLE revelation")
        logger.bind(sensitive=True).error(f"Failed to parse PoDLE revelation: {e}")
        return None


def deserialize_revelation(revelation_str: str) -> dict[str, Any] | None:
    """
    Deserialize PoDLE revelation from wire format.

    Format: utxo|P|P2|sig|e (pipe-separated strings)
    """
    try:
        if len(revelation_str) > _MAX_PODLE_REVELATION_LENGTH:
            logger.warning("PoDLE revelation exceeds maximum length")
            return None

        parts = revelation_str.split("|")
        if len(parts) != 5:
            logger.warning(f"Invalid revelation format: expected 5 parts, got {len(parts)}")
            return None

        revelation = {
            "utxo": parts[0],
            "P": parts[1],
            "P2": parts[2],
            "sig": parts[3],
            "e": parts[4],
        }
        if not _has_valid_revelation_field_lengths(revelation):
            return None

        return revelation

    except Exception as e:
        logger.error("Failed to deserialize PoDLE revelation")
        logger.bind(sensitive=True).error(f"Failed to deserialize PoDLE revelation: {e}")
        return None


def serialize_revelation(commitment: PoDLECommitment) -> str:
    """
    Serialize PoDLE revelation to wire format.

    Format: utxo|P|P2|sig|e (pipe-separated strings)
    """
    return "|".join(
        [
            commitment.utxo,
            commitment.p.hex(),
            commitment.p2.hex(),
            commitment.sig.hex(),
            commitment.e.hex(),
        ]
    )
