def _classify_unsupported_scriptpubkey(spk: bytes) -> str:
    """Return the recognizable family of an unsupported scriptPubKey."""
    if len(spk) == 34:
        if spk.startswith(b"\x00\x20"):
            return "P2WSH"
        if spk.startswith(b"\x51\x20"):
            return "P2TR"

    # Bare compressed or uncompressed pay-to-public-key output.
    if ((len(spk) == 35 and spk[0] == 0x21) or (len(spk) == 67 and spk[0] == 0x41)) and spk[
        -1
    ] == 0xAC:
        return "P2PK"

    if spk.startswith(b"\x6a"):
        return "OP_RETURN"

    # Native witness programs have a version opcode followed by one canonical push.
    if len(spk) >= 4 and (spk[0] == 0x00 or 0x51 <= spk[0] <= 0x60) and spk[1] == len(spk) - 2:
        witness_version = 0 if spk[0] == 0x00 else spk[0] - 0x50
        return f"witness v{witness_version}"

    return "nonstandard"


def verify_podle_binding(p: bytes, scriptpubkey: bytes | str) -> tuple[bool, str]:
    """
    Verify that a PoDLE public key ``P`` actually controls a given UTXO.

    The PoDLE proof on its own only shows that ``P`` and ``P2`` share a
    discrete log; it does NOT tie ``P`` to the UTXO the taker claims to be
    spending. Without this binding a taker could replay a stranger's UTXO as
    its anti-snooping commitment. This helper closes that gap by reconstructing
    the scriptPubKey that ``P`` would produce for each supported output type and
    comparing it against the UTXO's on-chain scriptPubKey.

    Supported script types: P2PKH, P2SH-P2WPKH, and P2WPKH (all using the
    33-byte compressed ``P``).

    Args:
        p: PoDLE public key ``P`` (33-byte compressed SEC1 encoding).
        scriptpubkey: UTXO scriptPubKey as raw bytes or a hex string.

    Returns:
        (is_bound, error_message)
    """
    if isinstance(scriptpubkey, str):
        try:
            spk = bytes.fromhex(scriptpubkey)
        except ValueError:
            return False, "scriptpubkey is not valid hex"
    else:
        spk = scriptpubkey

    if len(p) != 33:
        return False, f"Invalid P length: {len(p)}, expected 33 (compressed)"

    # BIP86 P2TR: P is the even-Y, parity-normalized output key.
    if len(spk) == 34 and spk[0] == 0x51 and spk[1] == 0x20:
        try:
            pubkey = CPubKey(p)
            if not pubkey.is_fullyvalid():
                raise ValueError("invalid public key")
        except ValueError:
            return False, "P is not a valid compressed secp256k1 public key"
        if p[0] != 0x02:
            return False, "P is not the even-Y BIP86 P2TR output key"
        if spk[2:] == p[1:]:
            return True, ""
        return False, "P does not match BIP86 P2TR scriptpubkey"

    h160 = hash160(p)

    # P2WPKH: OP_0 <20-byte hash160(P)>
    if len(spk) == 22 and spk[0] == 0x00 and spk[1] == 0x14:
        if spk[2:] == h160:
            return True, ""
        return False, "P does not match P2WPKH scriptpubkey"

    # P2PKH: OP_DUP OP_HASH160 <20-byte hash160(P)> OP_EQUALVERIFY OP_CHECKSIG
    if (
        len(spk) == 25
        and spk[0] == 0x76
        and spk[1] == 0xA9
        and spk[2] == 0x14
        and spk[23] == 0x88
        and spk[24] == 0xAC
    ):
        if spk[3:23] == h160:
            return True, ""
        return False, "P does not match P2PKH scriptpubkey"

    # P2SH-P2WPKH: OP_HASH160 <hash160(0x0014||hash160(P))> OP_EQUAL
    if len(spk) == 23 and spk[0] == 0xA9 and spk[1] == 0x14 and spk[22] == 0x87:
        redeem_script = b"\x00\x14" + h160
        if spk[2:22] == hash160(redeem_script):
            return True, ""
        return False, "P does not match P2SH-P2WPKH scriptpubkey"

    family = _classify_unsupported_scriptpubkey(spk)
    return False, f"Unsupported {family} scriptpubkey for PoDLE binding ({len(spk)} bytes)"


def verify_podle(
    p: bytes,
    p2: bytes,
    sig: bytes,
    e: bytes,
    commitment: bytes,
    index_range: range = range(10),
) -> tuple[bool, str]:
    """
    Verify PoDLE proof.

    Verifies that P and P2 have the same discrete log (private key)
    without revealing the private key itself.

    Args:
        p: Public key bytes (33 bytes compressed)
        p2: Commitment public key bytes (33 bytes compressed)
        sig: Signature s value (32 bytes)
        e: Challenge e value (32 bytes)
        commitment: sha256(P2) commitment (32 bytes)
        index_range: Allowed NUMS indices to try

    Returns:
        (is_valid, error_message)
    """
    try:
        if len(p) != 33:
            return False, f"Invalid P length: {len(p)}, expected 33"
        if len(p2) != 33:
            return False, f"Invalid P2 length: {len(p2)}, expected 33"
        if len(sig) != 32:
            return False, f"Invalid sig length: {len(sig)}, expected 32"
        if len(e) != 32:
            return False, f"Invalid e length: {len(e)}, expected 32"
        if len(commitment) != 32:
            return False, f"Invalid commitment length: {len(commitment)}, expected 32"

        expected_commitment = hashlib.sha256(p2).digest()
        if commitment != expected_commitment:
            return False, "Commitment does not match H(P2)"

        p_point = CPubKey(p)
        p2_point = CPubKey(p2)
        if not p_point.is_fullyvalid() or not p2_point.is_fullyvalid():
            return False, "Invalid public key"

        s_int = int.from_bytes(sig, "big")
        e_int = int.from_bytes(e, "big")

        if s_int == 0 or s_int >= SECP256K1_N:
            return False, "Signature value out of range"

        # sg = s * G
        sg = scalar_mult_g(s_int) if s_int > 0 else None

        # Compute -e mod N for subtraction (JAM compatible: s = k + e*x, verify Kg = s*G - e*P)
        minus_e_int = (-e_int) % SECP256K1_N

        for index in index_range:
            try:
                j = get_nums_point(index)

                # Kg = s*G - e*P = s*G + (-e)*P (JAM compatible verification)
                minus_e_p = point_mult(minus_e_int, p_point)
                kg = point_add(sg, minus_e_p) if sg is not None else minus_e_p

                # Kj = s*J - e*P2 = s*J + (-e)*P2
                minus_e_p2 = point_mult(minus_e_int, p2_point)
                if s_int > 0:
                    sj = point_mult(s_int, j)
                    kj = point_add(sj, minus_e_p2)
                else:
                    kj = minus_e_p2

                kg_bytes = point_to_bytes(kg)
                kj_bytes = point_to_bytes(kj)

                e_check = hashlib.sha256(kg_bytes + kj_bytes + p + p2).digest()

                if e_check == e:
                    logger.debug(f"PoDLE verification successful at index {index}")
                    return True, ""

            except Exception as ex:
                logger.bind(sensitive=True).debug(
                    f"PoDLE verification failed at index {index}: {ex}"
                )
                continue

        return False, f"PoDLE verification failed for all indices in {index_range}"

    except Exception as ex:
        logger.error("PoDLE verification error")
        logger.bind(sensitive=True).error(f"PoDLE verification error: {ex}")
        return False, f"Verification error: {ex}"


